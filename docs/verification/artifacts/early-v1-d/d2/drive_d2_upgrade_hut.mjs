import fs from 'node:fs';
import path from 'node:path';
import { connectDriver, sleep } from '../../res1d2-natural-mouse-driver.mjs';
const OUT = path.resolve('docs/verification/artifacts/early-v1-d/d2');
const log = (obj) => fs.appendFileSync(path.join(OUT, 'events-second-life.jsonl'), JSON.stringify({ utc: new Date().toISOString(), ...obj }) + '\n');
const d = await connectDriver({ cdpPort: 9242, matchPort: '4380' });
await d.bringToFront();
log({ kind: 'click-upgrade-hut', ...await d.click({ x: 918, y: 312 }) });
await sleep(1500);
await d.screenshot(path.join(OUT, 'second-life-hut-l2.png'));
const save = await d.readSave();
log({ kind: 'save-hut-l2', revision: save.revision, total: save.state?.total_elapsed_seconds, lingli: save.state?.resources?.lingli?.value, money: save.state?.resources?.money?.value, buildings: save.state?.buildings });
await d.close();
