import fs from 'node:fs';
import path from 'node:path';
import { connectDriver, sleep } from '../../res1d2-natural-mouse-driver.mjs';
const OUT = path.resolve('docs/verification/artifacts/early-v1-d/d2');
const log = (obj) => fs.appendFileSync(path.join(OUT, 'events-second-life.jsonl'), JSON.stringify({ utc: new Date().toISOString(), ...obj }) + '\n');
const d = await connectDriver({ cdpPort: 9242, matchPort: '4380' });
await d.bringToFront();
log({ kind: 'click-build-wooden-house', ...await d.click({ x: 910, y: 453 }) });
await sleep(1500);
await d.screenshot(path.join(OUT, 'second-life-wooden-house.png'));
await sleep(20000);
await d.screenshot(path.join(OUT, 'second-life-steady-20s.png'));
const save = await d.readSave();
fs.writeFileSync(path.join(OUT, 'save-second-life-operable.json'), JSON.stringify(save, null, 2));
log({ kind: 'save-operable', revision: save.revision, total: save.state?.total_elapsed_seconds, era: save.state?.era_id, level: save.state?.level, rc: save.state?.reincarnation_count, dh: save.state?.dao_heart, highest: save.state?.highest_era, buildings: save.state?.buildings, resources: save.state?.resources, achievements: save.state?.achievements });
await d.close();
