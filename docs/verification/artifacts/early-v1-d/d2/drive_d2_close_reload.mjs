import fs from 'node:fs';
import path from 'node:path';
import { connectDriver, sleep } from '../../res1d2-natural-mouse-driver.mjs';
const OUT = path.resolve('docs/verification/artifacts/early-v1-d/d2');
const log = (obj) => fs.appendFileSync(path.join(OUT, 'events-second-life.jsonl'), JSON.stringify({ utc: new Date().toISOString(), ...obj }) + '\n');
const d = await connectDriver({ cdpPort: 9242, matchPort: '4380' });
await d.bringToFront();
log({ kind: 'click-close-after-reload', ...await d.click({ x: 270, y: 292 }) });
await sleep(1500);
await d.screenshot(path.join(OUT, 'reload-after-close.png'));
const save = await d.readSave();
log({ kind: 'save-reload-final', revision: save.revision, total: save.state?.total_elapsed_seconds, rc: save.state?.reincarnation_count, dh: save.state?.dao_heart, highest: save.state?.highest_era, buildings: save.state?.buildings });
await d.close();
